@dataclass(frozen=True)
class Hop:
    carrier: str
    origin: str
    destination: str
    minutes: int


@dataclass(frozen=True)
class Template:
    hops: tuple[Hop, ...]
    layovers: tuple[int, ...]  # minutes between hops
    depart: time
    oneway_price: float  # GBP


def T(carrier_hops: list[tuple[str, str, str, int]], layovers: list[int], dep: str, price: float) -> Template:
    h, m = map(int, dep.split(":"))
    return Template(tuple(Hop(*x) for x in carrier_hops), tuple(layovers), time(h, m), price)


def _ret(r: float) -> float:
    """One-way equivalent of a return fare (return = 2 x one-way x 0.8)."""
    return round(r / 1.6, 2)


