def _templates(origin: str, destination: str) -> list[Template]:
    if (origin, destination) in ROUTES:
        return ROUTES[(origin, destination)]
    rev = ROUTES.get((destination, origin))
    if not rev:
        return []
    out = []
    for i, t in enumerate(rev):
        hops = tuple(Hop(h.carrier, h.destination, h.origin, h.minutes) for h in reversed(t.hops))
        # Mirror departures to a different, plausible time of day.
        dep = time((t.depart.hour + 9 + 2 * i) % 24, t.depart.minute)
        out.append(Template(hops, tuple(reversed(t.layovers)), dep, t.oneway_price))
    return out


def _jitter(key: str) -> float:
    h = int(hashlib.sha256(key.encode()).hexdigest(), 16)
    return 1 + ((h % 9) - 4) / 100  # +/- 4%


def _legs(t: Template, day: date) -> list[Leg]:
    legs: list[Leg] = []
    clock = datetime.combine(day, t.depart)  # local time at the hop's origin
    for i, hop in enumerate(t.hops):
        arrive = (
            clock
            + timedelta(minutes=hop.minutes)
            + timedelta(hours=UTC_OFFSET.get(hop.destination, 0) - UTC_OFFSET.get(hop.origin, 0))
        )
        legs.append(
            Leg(
                carrier=hop.carrier,
                flight_number=f"{hop.carrier[:2].upper()}{100 + i}",
                origin=hop.origin,
                destination=hop.destination,
                depart=clock,
                arrive=arrive,
                duration_min=hop.minutes,
            )
        )
        if i < len(t.layovers):
            clock = arrive + timedelta(minutes=t.layovers[i])
    return legs


class FixtureProvider:
    name = "fixture"

    async def search(self, slices: list[Slice], max_results: int = 5) -> list[Ticket]:
        per_slice = [_templates(s.origin, s.destination) for s in slices]
        if any(not ts for ts in per_slice):
            return []
        tickets: list[Ticket] = []
        for combo in itertools.product(*per_slice):
            price = sum(t.oneway_price for t in combo) * (0.8 if len(slices) > 1 else 1.0)
            price *= _jitter("|".join(f"{s.origin}{s.destination}{s.date}" for s in slices) + str(combo[0].depart))
            if slices[0].date.weekday() == 5:  # Saturdays are busy
                price *= 1.12
            tickets.append(
                Ticket(
                    provider=self.name,
                    price=round(price, 2),
                    journeys=[_legs(t, s.date) for t, s in zip(combo, slices, strict=True)],
                )
            )
        tickets.sort(key=lambda t: t.price)
        return tickets[:max_results]


class FixtureCache:
    """Stale, slightly optimistic lowest prices, like a real fare cache."""

    name = "fixture-cache"

    async def lowest_price(self, origin, destination, depart, return_date=None):  # noqa: ANN001
        ts = _templates(origin, destination)
        if not ts:
            return None
        one_way = min(t.oneway_price for t in ts)
        return round((one_way * 1.6 if return_date else one_way) * 0.95, 2)
